async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const browser = await chromium.launch();
  // 1x keeps the payload small enough to stay inside the latency budget while
  // the signage text remains large enough to read.
  const page = await browser.newPage({ viewport: { width: 760, height: 1000 }, deviceScaleFactor: 1 });

  const shots = [
    { name: "menu-malaysia.png", html: MENU_HTML, selector: ".sign" },
    { name: "campus-singapore.png", html: CAMPUS_HTML, selector: ".board" },
    { name: "mixed-chat.png", html: CHAT_HTML, selector: ".phone" },
  ];

  for (const shot of shots) {
    await page.setContent(shot.html, { waitUntil: "load" });
    const buffer = await page.locator(shot.selector).screenshot({ type: "png" });
    const target = path.join(OUT_DIR, shot.name);
    await writeFile(target, buffer);
    console.log(`fixture written: ${path.relative(process.cwd(), target)} (${Math.round(buffer.length / 1024)} kB)`);
  }

  await browser.close();
  await writeFile(path.join(OUT_DIR, "README.md"), README);
  if (!existsSync(path.join(OUT_DIR, "menu-malaysia.png"))) process.exitCode = 1;
}

main().catch((error) => {
  console.error("fixture generation failed:", error.message);
  process.exitCode = 1;
});
